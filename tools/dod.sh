#!/bin/sh
#
# Definition of Done — последний гейт перед сдачей.
#
# Отвечает на два вопроса подряд, и порядок важен:
#
#   1. Все ли критерии приёмки отмечены выполненными
#   2. Зелёный ли полный гейт
#
# Сначала постановка, потом код. Обратный порядок дал бы зелёный прогон
# с невыполненными пунктами — то есть работу, которая проходит проверку,
# не сделав того, о чём договаривались.
#
# Где лежит очередь, сообщает ядро переменной DELTA_TASKS_DIR. Разбирать
# раскладку установки здесь нельзя: в соседнем стеке она уже однажды
# разошлась с ядром, и первый живой прогон упал на «задача не найдена»,
# хотя задача лежала там, где её искало ядро. Одно знание — один дом.

set -u

TASK="${1:-${DELTA_TASK:-}}"
case "$TASK" in
    T-[0-9][0-9][0-9][0-9]) ;;
    *)
        echo "Нужен номер задачи вида T-0001. Получено: «$TASK»." >&2
        exit 2
        ;;
esac

QUEUE="${DELTA_TASKS_DIR:-}"
if [ -z "$QUEUE" ] || [ ! -d "$QUEUE" ]; then
    echo "Не найден каталог очереди. Ядро сообщает его переменной DELTA_TASKS_DIR;" >&2
    echo "сейчас там «$QUEUE». Если запускаешь вручную — задай её:" >&2
    echo "  DELTA_TASKS_DIR=<путь> sh tools/dod.sh $TASK" >&2
    exit 2
fi

FILE=$(ls "$QUEUE/$TASK"-*.md 2>/dev/null | head -1)
if [ -z "$FILE" ]; then
    echo "Задача $TASK в очереди $QUEUE не найдена." >&2
    exit 2
fi

UNCHECKED=$(grep -c '^- \[ \]' "$FILE" 2>/dev/null || echo 0)
if [ "$UNCHECKED" -gt 0 ]; then
    echo "Не выполнено пунктов: $UNCHECKED"
    grep '^- \[ \]' "$FILE" | sed 's/^- \[ \] /  • /'
    echo
    echo "FIX: сделай то, о чём говорит пункт, и поставь «- [x]». Пункт, который"
    echo "     оказался неприменим, объясняется в отчёте, а не молча отмечается."
    exit 1
fi

echo "✓ $TASK: все пункты отмечены"
echo

DIR=$(dirname "$0")
sh "$DIR/verify.sh" full
